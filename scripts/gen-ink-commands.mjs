// The ink command grid, plus the two readable files that describe it.
//
// A name is a better interface than a parser: /ink-note-project says what it does before it is
// typed. Ten categories times four depths is forty combinations, so they are generated from this
// one template instead of written by hand, together with commands/COMMANDS.md and
// commands/manifest.json, which are the same rows in a form a person and a program can both read.
//
//   npm run gen:commands
//
// Every command it writes is a thin wrapper: it names the preset and hands the writing to
// skills/ink/SKILL.md, which stays the only place the rules live. Rerunning it is safe, and it
// leaves ink-threads.md, ink-split.md, ink-draft.md and ink-push.md alone, because those are a unit
// or a phase rather than a depth plus a shelf.

import { writeFileSync } from 'node:fs';

const CATS = ['work', 'project', 'learning', 'thought', 'quote', 'task', 'deadline', 'life', 'class', 'inbox'];

const DEPTHS = {
  brief: { does: 'a line or two', mode: 'refine', shape: 'one or two sentences, no markup' },
  note: { does: 'a short paragraph or two', mode: 'refine', shape: 'three to eight sentences, one or two plain paragraphs' },
  detail: { does: 'a few paragraphs, with the decision and the blocker', mode: 'refine', shape: 'two to four paragraphs, roughly 900 to 2,000 characters, with the decision, the alternative rejected and the exact blocker named' },
  guide: { does: 'a written-up method', mode: 'verbatim', shape: 'a written-up method of roughly 1,500 to 3,800 characters, an opening paragraph, then bullets and paragraphs' },
};

const title = (word) => word[0].toUpperCase() + word.slice(1);
const rows = [];
let written = 0;

function command(depth, cat) {
  const where = cat ? ', category `' + cat + '`' : '';
  const guard = depth === 'guide' ? ', mode `verbatim`, because the cleanup would flatten the structure' : '';
  const due = cat === 'deadline'
    ? '\nA deadline needs a date. Pass `due:YYYY-MM-DD`, and ask for it rather than filing a reminder\nthat cannot remind anything.\n'
    : '';
  const heading = cat ? 'a ' + depth + ' note under ' + title(cat) : 'a ' + depth + ' note';
  const shape = 'Use the `ink` skill. Unit `one`, depth `' + depth + '`' + where + guard + ': ' + DEPTHS[depth].shape + '.';
  return [
    '---',
    'description: File this session as ' + heading,
    'argument-hint: [what to write about]',
    '---',
    '',
    shape,
    due,
    'The subject, when the command was given one: $ARGUMENTS',
    '',
    'File it as one request, report the receipt, and stop.',
    '',
  ].join('\n');
}

const write = (name, body) => {
  writeFileSync('commands/' + name + '.md', body);
  written += 1;
};

for (const depth of Object.keys(DEPTHS)) {
  write('ink-' + depth, command(depth, null));
  rows.push({ command: '/ink-' + depth, unit: 'one', depth, category: null, mode: DEPTHS[depth].mode,
    does: DEPTHS[depth].does + ', category from the session' });
  for (const cat of CATS) {
    write('ink-' + depth + '-' + cat, command(depth, cat));
    rows.push({ command: '/ink-' + depth + '-' + cat, unit: 'one', depth, category: cat, mode: DEPTHS[depth].mode,
      does: DEPTHS[depth].does + ' about ' + cat });
  }
}

for (const cat of CATS) {
  write('ink-' + cat, command('brief', cat));
  rows.push({ command: '/ink-' + cat, unit: 'one', depth: 'brief', category: cat, mode: 'refine',
    does: 'a line or two about ' + cat + (cat === 'deadline' ? ', asks for due:' : '') });
}

const manual = [
  { command: '/ink-draft', unit: 'draft', depth: null, category: null, mode: null,
    does: 'drafts the session into .ink/draft.md, revises on request, sends nothing' },
  { command: '/ink-push', unit: 'push', depth: null, category: null, mode: null,
    does: 'sends the reviewed draft in one request, then archives it' },
  { command: '/ink-split', unit: 'split', depth: 'note', category: null, mode: 'refine',
    does: 'one note per distinct decision or topic' },
  { command: '/ink-threads', unit: 'threads', depth: 'note', category: null, mode: 'refine',
    does: 'one note per separate line of work' },
];
for (const row of manual) rows.push(row);

rows.sort((a, b) => a.command.localeCompare(b.command));

const cell = (value) => (value ? '`' + value + '`' : '-');
const table = [
  '# INK commands',
  '',
  'Generated by `scripts/gen-ink-commands.mjs`. Edit the generator, not this file.',
  '',
  rows.length + ' commands. Each one is a thin wrapper around `skills/ink/SKILL.md`.',
  '',
  '| Command | Unit | Depth | Category | Mode | What it does |',
  '| --- | --- | --- | --- | --- | --- |',
  ...rows.map((r) => '| `' + r.command + '` | ' + r.unit + ' | ' + cell(r.depth) + ' | ' + (r.category ?? '-') + ' | ' + cell(r.mode) + ' | ' + r.does + ' |'),
  '',
].join('\n');
writeFileSync('commands/COMMANDS.md', table);
writeFileSync('commands/manifest.json', JSON.stringify(rows, null, 2) + '\n');

console.log(rows.length + ' commands described, ' + written + ' wrapper files written to commands/');
